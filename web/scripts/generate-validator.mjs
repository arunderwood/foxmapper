#!/usr/bin/env node
/**
 * Generates web/src/log/report-validator.gen.js from docs/schema/report.v1.schema.json.
 *
 * Compiled here rather than in the browser: Ajv compiles a schema to source and evaluates it with
 * `new Function`, and the CSP's `script-src 'self'` carries no 'unsafe-eval'. Standalone output is
 * an ordinary module, so the runtime ships the validator and none of Ajv.
 *
 * The output is committed so the generated code is reviewed like any other. `--check` regenerates
 * in memory and fails if the committed file differs — CI runs it, so the schema and the validator
 * cannot drift apart.
 */
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA = join(WEB, '..', 'docs', 'schema', 'report.v1.schema.json');
const OUT = join(WEB, 'src', 'log', 'report-validator.gen.js');

const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'));

const ajv = new Ajv2020({
  // Strict mode throws on anything Ajv would otherwise ignore — an unknown keyword, a misspelt
  // `required` — so a schema mistake fails generation instead of quietly validating less.
  strict: true,
  allowUnionTypes: true,
  discriminator: true,
  code: { source: true, esm: true, lines: true },
});

const header = [
  '// GENERATED by scripts/generate-validator.mjs from docs/schema/report.v1.schema.json.',
  '// Do not edit. Regenerate: node scripts/generate-validator.mjs',
  '',
].join('\n');
const generated = header + standaloneCode(ajv, ajv.compile(schema));

// Runtime helpers would be imported from Ajv, making it a production dependency of the bundle.
if (/from\s+["']ajv/.test(generated)) {
  console.error(
    'The generated validator imports from ajv. Remove the schema keyword that needs it.',
  );
  process.exit(1);
}

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(OUT, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (committed !== generated) {
    console.error(
      'src/log/report-validator.gen.js is out of date with docs/schema/report.v1.schema.json.\n' +
        'Run: node scripts/generate-validator.mjs',
    );
    process.exit(1);
  }
} else {
  writeFileSync(OUT, generated);
}
